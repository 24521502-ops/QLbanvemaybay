-- 1. AIRLINE
CREATE OR REPLACE TRIGGER TRG_AIRLINE_ID 
BEFORE INSERT ON AIRLINE 
FOR EACH ROW 
BEGIN IF :NEW.AirlineID IS NULL THEN :NEW.AirlineID := 'AL' || LPAD(SEQ_AIRLINE.NEXTVAL,6,'0'); END IF; END;


